"""The Percolator model's tables for the firmware: overlay/firmware/src/fx_perc_tab.h from perc_params.py (pure Python).
   python3 tools/fxlab/gen_perc_tab.py [OUT.h]     (tests/test_perc.py checks the committed header is what this writes)"""
import math
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import gen_hm2_tab as H  # noqa: E402  (arr, clip_tab, G)
import perc_params as P  # noqa: E402


def interp(x, xs, ys):
    for (x0, y0), (x1, y1) in zip(zip(xs, ys), zip(xs[1:], ys[1:])):
        if x0 <= x <= x1:
            return y0 + (y1 - y0) * (x - x0) / (x1 - x0)
    return ys[-1]


def text():
    gain, hpg = [], []
    for i in range(128):
        p = i / 127.0
        gain.append(int(round(1024 * 10 ** (interp(p, P.POT, P.PASS_DB) / 20))))
        hpg.append(H.G(interp(p, P.POT, P.HP_HZ)))
    c1p, c1n, c1k, tau = P.FIT["c1"]
    o = ["/* Generated by tools/fxlab/gen_perc_tab.py from tools/fxlab/perc_params.py: the Harmonic Percolator model's tables. Do not edit. */",
         "#define PC_STEP1 256                       /* the collector clip: 1/16 V a step, 0 .. 8 V */",
         "#define PC_STEPM 64                        /* the MODE clips: 1/64 V a step, 0 .. 2 V */",
         f"#define PC_SERVO {int(round(65536 / (tau * H.FS)))}                      /* Q16: the collector clip's mean follower */",
         f"#define PC_G_C6 {H.G(P.C6_HZ)}",
         H.arr("PC_GAIN", gain, "int32_t", 8), H.arr("PC_HPG", hpg, "uint16_t"),
         H.arr("PC_C1P", H.clip_tab(c1p, c1k, 256)), H.arr("PC_C1N", H.clip_tab(c1n, c1k, 256))]
    for nm in ("GE", "SI"):
        a, b, k = P.FIT[nm]
        o.append(H.arr(f"PC_{nm}P", H.clip_tab(a, k, 64)))
        o.append(H.arr(f"PC_{nm}N", H.clip_tab(b, k, 64)))
    return "\n".join(o) + "\n"


if __name__ == "__main__":
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).resolve().parents[2] / "overlay/firmware/src/fx_perc_tab.h"
    out.write_text(text())
    print(f"gen_perc_tab: {out}")
