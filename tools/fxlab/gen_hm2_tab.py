"""The HM-2 model's tables for the firmware: overlay/firmware/src/fx_hm2_tab.h from hm2_params.py (pure Python).
   python3 tools/fxlab/gen_hm2_tab.py [OUT.h]     (tests/test_hm2.py checks the committed header is what this writes)

Voltages are Q12 (4096 = 1 V) before the tone stage, Q16 in it; one-pole coefficients are G = g / (1 + g), g = tan(pi f / 44100), Q16."""
import math
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import hm2_params as P  # noqa: E402

FS = 44100.0


def clip_tab(lim, knee, step, n=129):
    """n entries of v / (1 + (v / lim)^knee)^(1 / knee) at v = i * step (Q12 volts), Q12"""
    out = []
    for i in range(n):
        v = i * step / 4096.0
        out.append(int(round(4096 * v / (1 + (v / lim) ** knee) ** (1.0 / knee))))
    return out


def gate_tab(vg, step, n=129):
    return [int(round(4096 * (v - vg * math.tanh(v / vg)))) for v in (i * step / 4096.0 for i in range(n))]


def g3_tab():
    out = []
    pts = list(zip(P.DIST_PTS, P.G3_DB))
    for i in range(128):
        d = i / 127.0
        if d <= pts[0][0]:
            db = pts[0][1]
        elif d >= pts[-1][0]:
            db = pts[-1][1]
        else:
            for (d0, g0), (d1, g1) in zip(pts, pts[1:]):
                if d0 <= d <= d1:
                    db = g0 + (g1 - g0) * (d - d0) / (d1 - d0)
        out.append(int(round(1024 * 10 ** (db / 20))))
    return out


def taper_db(i):
    u = 2 * i / 127.0 - 1
    return P.EQ_MAX_DB * math.copysign(abs(u) ** P.EQ_TAPER, u)


def eq_tab(f0, q, share):
    """per pot position 0 .. 127: a1, a2 (Q16) and c (Q13) of the SVF peaking form y = x + c * bp1"""
    g = math.tan(math.pi * f0 / FS)
    rows = []
    for i in range(128):
        a = 10 ** (share * taper_db(i) / 40)
        k = 1.0 / (a * q)
        a1 = 1.0 / (1 + g * (g + k))
        rows.append((int(round(a1 * 65536)), int(round(g * a1 * 65536)), int(round((a * a - 1) * k * 8192))))
    return int(round(g * 65536)), rows


def G(f):
    g = math.tan(math.pi * f / FS)
    return int(round(65536 * g / (1 + g)))


def arr(name, vals, ctype="int16_t", per=12):
    lines = [f"static const {ctype} {name}[{len(vals)}] = {{"]
    for i in range(0, len(vals), per):
        lines.append("    " + ", ".join(str(v) for v in vals[i:i + per]) + ",")
    lines.append("};")
    return "\n".join(lines)


def text():
    o = ["/* Generated by tools/fxlab/gen_hm2_tab.py from tools/fxlab/hm2_params.py: the HM-2 model's tables. Do not edit. */",
         "#define HM2_STEP12 512                     /* clip 1 and 2: 1/8 V a step, 0 .. 16 V */",
         "#define HM2_STEP3 64                       /* clip 3: 1/64 V a step, 0 .. 2 V */",
         "#define HM2_STEPG 16                       /* the gate: 1/256 V a step, 0 .. 0.5 V */",
         f"#define HM2_GATE_V {int(round(4096 * P.GATE_V))}                      /* its dead zone's V, Q12 */",
         f"#define HM2_PRE_GAIN {int(round(1024 * 10 ** (P.C3_GAIN_DB / 20) / 32))}                  /* x (32768 = 0.25 V) to Q12 volts at the first stage, Q10 */",
         f"#define HM2_SERVO {int(round(65536 / (P.SERVO_TAU * FS)))}                     /* Q16: the first clip's mean follower */",
         f"#define HM2_G_HP1 {G(P.C3_HP[0])}\n#define HM2_G_HP2 {G(P.C3_HP[1])}\n#define HM2_G_LP1 {G(P.C3_LP[0])}\n#define HM2_G_LP2 {G(P.C3_LP[1])}",
         f"#define HM2_G_C10 {G(P.C10_HZ)}\n#define HM2_G_POSTLP {G(P.POST_LP_HZ)}\n#define HM2_G_POSTHP {G(P.POST_HP_HZ)}"]
    for nm, (pl, nl, kn) in (("1", P.CLIP1), ("2", P.CLIP2)):
        o.append(arr(f"HM2_CLIP{nm}P", clip_tab(pl, kn, 512)))
        o.append(arr(f"HM2_CLIP{nm}N", clip_tab(nl, kn, 512)))
    o.append(arr("HM2_CLIP3", clip_tab(P.CLIP3[0], P.CLIP3[2], 64)))
    o.append(arr("HM2_GATE", gate_tab(P.GATE_V, 16)))
    o.append(arr("HM2_G3", g3_tab(), "uint16_t"))
    for nm, spec in (("LOW", P.EQ_LOW), ("MID", P.EQ_MID), ("HIGH", P.EQ_HIGH)):
        g, rows = eq_tab(*spec)
        o.append(f"#define HM2_EQ_{nm}_G {g}                  /* g = tan(pi f / fs), Q16 */")
        o.append(arr(f"HM2_EQ_{nm}", [v for r in rows for v in r], "int32_t", 9))
    return "\n".join(o) + "\n"


if __name__ == "__main__":
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).resolve().parents[2] / "overlay/firmware/src/fx_hm2_tab.h"
    out.write_text(text())
    print(f"gen_hm2_tab: {out}")
