"""The Dragonfly Room port's tables for the firmware: overlay/firmware/src/fx_dfly_tab.h (pure Python), at the reverb's 22.05 kHz.
   python3 tools/fxlab/gen_dfly_tab.py [OUT.h]     (tests/test_dfly.py checks the committed header is what this writes)
The fixed filters of Freeverb3's earlyref / progenitor2 as Dragonfly sets them, the DAMP knob's filters, the LFOs, the decay constants."""
import math
import sys
from pathlib import Path

FS = 22050.0


def iir1_lpf(fc):
    t = math.tan(math.pi * min(fc, 0.45 * FS) / FS)
    return int(round(32768 * t / (1 + t))), int(round(32768 * (1 - t) / (1 + t)))


def alpha_bw(fc, bw):
    w = 2 * math.pi * fc / FS
    sn = math.sin(w)
    return sn * math.sinh(math.log(2) / 2.0 * bw * w / sn)


def bq_lpf(fc, bw):
    w = 2 * math.pi * fc / FS
    cs = math.cos(w)
    al = alpha_bw(fc, bw)
    a0 = 1.0 / (1.0 + al)
    return [a0 * (1 - cs) * 0.5, a0 * (1 - cs), a0 * (1 - cs) * 0.5, a0 * -2 * cs, a0 * (1 - al)]


def bq_apf(fc, bw):
    w = 2 * math.pi * fc / FS
    cs = math.cos(w)
    al = alpha_bw(fc, bw)
    a0 = 1.0 / (1.0 + al)
    return [a0 * (1 - al), a0 * -2 * cs, a0 * (1 + al), a0 * -2 * cs, a0 * (1 - al)]


def q14(v):
    return [int(round(x * 16384)) for x in v]


def arr(name, vals, ctype="int16_t", per=10):
    lines = [f"static const {ctype} {name}[{len(vals)}] = {{"]
    for i in range(0, len(vals), per):
        lines.append("    " + ", ".join(str(v) for v in vals[i:i + per]) + ",")
    lines.append("};")
    return "\n".join(lines)


def damp_fc(i):
    return 10000.0 * (3000.0 / 10000.0) ** (i / 127.0)       # the DAMP knob: 10 kHz (the Medium Clear Room's early damp) .. 3 kHz: the filters stay under 0.46 Nyquist


def text():
    o = ["/* Generated by tools/fxlab/gen_dfly_tab.py: the Dragonfly Room port's tables (22.05 kHz). Do not edit. */"]
    b, a = iir1_lpf(20000)
    o.append(f"#define DFR_LPIN_B {b}\n#define DFR_LPIN_A {a}                 /* the input damp: 20 kHz, held under the Nyquist */")
    for nm, fc in (("LFO1L", 20.0), ("LFO2L", 12.0)):
        b, a = iir1_lpf(fc)
        o.append(f"#define DFR_{nm}_B {b}\n#define DFR_{nm}_A {a}")
    c = 2 * 5.0 / FS
    gain = (math.sqrt(3.0) - 2.0 * math.sin(math.pi * c)) / (math.sin(math.pi * c) + math.sqrt(3.0) * math.cos(math.pi * c))
    o.append(f"#define DFR_DCGAIN {int(round(gain * 32768))}                 /* the input's DC cut, 5 Hz */")
    spin2 = math.sqrt(100.0 - (10.0 - 0.8) ** 2) / 2.0
    o.append(f"#define DFR_INC1 {int(round(0.8 / FS * 2 ** 32))}u             /* the allpasses' LFO, 0.8 Hz */")
    o.append(f"#define DFR_INC2 {int(round(spin2 / FS * 2 ** 32))}u             /* the output combs' LFO, {spin2:.2f} Hz */")
    o.append(f"#define DFR_WANDER {int(round((40 / 200.0 + 0.1) * 32768))}                /* Q15: 40 / 200 + 0.1 */")
    for nm, fc in (("EAP1", 750.0), ("EAP2", 150.0)):
        o.append(arr(f"DFR_{nm}", q14(bq_apf(fc, 4)), "int16_t", 5) + "  /* b0 b1 b2 a1 a2, Q14 */")
    o.append(arr("DFR_BASSAP", q14(bq_apf(150.0, 4)), "int16_t", 5))
    o.append(arr("DFR_BASSLP", q14(bq_lpf(600.0, 2.0)), "int16_t", 5))
    # the DAMP knob: the late damp (0.94 of it), the early damp, the output filter at the late damp
    lb, la, eb, ea, ob = [], [], [], [], []
    for i in range(128):
        fc = damp_fc(i)
        x, y = iir1_lpf(fc * 0.94)
        lb.append(x), la.append(y)
        x, y = iir1_lpf(fc * 1.06)
        eb.append(x), ea.append(y)
        ob += q14(bq_lpf(min(fc * 0.94, FS / 2.5), 2.0))
    o += [arr("DFR_DAMPL_B", lb, "int16_t"), arr("DFR_DAMPL_A", la, "int16_t"), arr("DFR_DAMPE_B", eb, "int16_t"), arr("DFR_DAMPE_A", ea, "int16_t"),
          arr("DFR_OUTLP", ob, "int16_t", 10)]
    L = [math.log2(v) for v in (0.237, 0.938, 0.844, 0.906)]
    o.append(arr("DFR_LOG2DEC", [int(round(v * 65536)) for v in L], "int32_t", 4) + "  /* log2 of decay0 .. decay3, Q16 */")
    return "\n".join(o) + "\n"


if __name__ == "__main__":
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).resolve().parents[2] / "overlay/firmware/src/fx_dfly_tab.h"
    out.write_text(text())
    print(f"gen_dfly_tab: {out}")
