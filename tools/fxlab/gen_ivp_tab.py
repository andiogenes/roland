"""The PRE model's tables for the firmware: overlay/firmware/src/fx_ivp_tab.h from ivp_params.py (pure Python).
   python3 tools/fxlab/gen_ivp_tab.py [OUT.h]     (tests/test_ivp.py checks the committed header is what this writes)"""
import math
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import gen_hm2_tab as H  # noqa: E402  (arr, G)
import ivp_params as P  # noqa: E402


def text():
    # a shelf's (G - 1) in Q12 per knob position (BASS and TREBLE -64 .. 63 stored as 0 .. 127)
    # a cut is the inverse of a boost: the bass shelf's corner moves up to fc / G, the treble's down to fc * G (G < 1)
    shelf, gb, gt = [], [], []
    for i in range(128):
        u = 2 * i / 127.0 - 1
        db = P.SHELF_DB * math.copysign(abs(u) ** P.SHELF_TAPER, u)
        g = 10 ** (db / 20)
        shelf.append(int(round(4096 * (g - 1))))
        gb.append(H.G(P.BASS_FC if g >= 1 else P.BASS_FC / g))
        gt.append(H.G(P.TREB_FC if g >= 1 else P.TREB_FC * g))
    drive = [int(round(1024 * P.DRIVE_MAX * (i / 127.0) ** 2)) for i in range(128)]
    # the pair: VSAT * tanh(v / VK) for v = 0 .. 0.5 V in 1/256 V steps (Q12 volts)
    pair = [int(round(4096 * P.PAIR_VSAT * math.tanh((i * 16 / 4096.0) / P.PAIR_VK))) for i in range(129)]
    o = ["/* Generated by tools/fxlab/gen_ivp_tab.py from tools/fxlab/ivp_params.py: the PRE model's tables. Do not edit. */",
         f"#define IV_G_HP {H.G(P.HP_HZ)}",
         f"#define IV_RANGE_LO {int(round(1024 * 10 ** (P.RANGE_DB[0] / 20)))}\n#define IV_RANGE_HI {int(round(1024 * 10 ** (P.RANGE_DB[1] / 20)))}      /* Q10 */",
         f"#define IV_VSAT {int(round(4096 * P.PAIR_VSAT))}                      /* Q12 volts */",
         f"#define IV_OUT {int(round(1024 * P.OUT_V * 32768 / 4096))}                      /* Q10: Q12 volts to a sample (x 0.3 of full scale a volt) */",
         H.arr("IV_SHELF", shelf, "int32_t", 8), H.arr("IV_GB", gb, "uint16_t"), H.arr("IV_GT", gt, "uint16_t"), H.arr("IV_DRIVE", drive, "int32_t", 8), H.arr("IV_PAIR", pair, "int16_t")]
    return "\n".join(o) + "\n"


if __name__ == "__main__":
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).resolve().parents[2] / "overlay/firmware/src/fx_ivp_tab.h"
    out.write_text(text())
    print(f"gen_ivp_tab: {out}")
